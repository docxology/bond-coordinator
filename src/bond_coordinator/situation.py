"""Lightweight HTML "situation room" for the BOND fleet.

A single self-contained HTML document (no external assets, no JavaScript)
listing every film package, its mission phase and timeline, measured coverage
(color-coded against the 90% gate), the suite-layer summary, the Q-branch
gadget inventory grouped per film, and the most recent ledger transitions.

Mirrors the exemplar dashboard pattern: pure string building, deterministic
given its inputs, everything HTML-escaped.  The rendered document is
disposable — it is regenerated by ``scripts/build_situation_room.py`` and
never hand-edited.
"""

from __future__ import annotations

from html import escape
from pathlib import Path

from .ledger import MissionLedger
from .registry import COORDINATOR_CODENAME, ROSTER, PackageRecord
from .status import LayerSummary, SuiteStatus
from .types import Gadget, GadgetRegistry, MissionPhase, PackageStatus

#: Recent-transition rows shown in the audit-trail timeline section.
AUDIT_TRAIL_LIMIT = 12

#: Coverage thresholds driving the heat coloring (aligned with COVERAGE_FLOOR).
_HEAT_FLOOR = 90.0
_HEAT_WARN = 50.0


def _fmt_coverage(coverage: float | None) -> str:
    return "—" if coverage is None else f"{coverage:.1f}%"


def _heat_class(coverage: float | None) -> str:
    """Coverage heat bucket: ok (≥90), warn (50–90), bad (<50), unknown."""
    if coverage is None:
        return "heat-unknown"
    if coverage >= _HEAT_FLOOR:
        return "heat-ok"
    if coverage >= _HEAT_WARN:
        return "heat-warn"
    return "heat-bad"


def _card(label: str, value: object) -> str:
    return (
        f'<div class="card"><span class="card-label">{escape(str(label))}</span>'
        f'<span class="card-value">{escape(str(value))}</span></div>'
    )


def _timeline_bar(phase: MissionPhase) -> str:
    """Five-cell lifecycle progress bar; completed phases filled, current marked."""
    cells: list[str] = []
    for candidate in MissionPhase:
        if candidate.phase_index < phase.phase_index:
            css = "tl-done"
        elif candidate is phase:
            css = "tl-now"
        else:
            css = "tl-todo"
        cells.append(
            f'<span class="{css}" title="{escape(candidate.value)}">'
            f"{candidate.phase_index + 1}</span>"
        )
    return f'<div class="timeline">{"".join(cells)}</div>'


def _package_rows(roster: tuple[PackageRecord, ...], ledger: MissionLedger) -> str:
    rows: list[str] = []
    for record in roster:
        entry = ledger.get(record.slug)
        phase = entry.phase
        rows.append(
            "<tr>"
            f"<td>{record.rank}</td>"
            f"<td><code>{escape(record.slug)}</code></td>"
            f"<td>{escape(record.film)} ({record.year})</td>"
            f"<td>{escape(record.codename)}</td>"
            f"<td>{escape(record.status.value)}</td>"
            f"<td>{escape(phase.value)}</td>"
            f"<td>{_timeline_bar(phase)}</td>"
            f"<td>{escape(entry.updated_at.isoformat())}</td>"
            f'<td class="{_heat_class(record.coverage)}">{_fmt_coverage(record.coverage)}</td>'
            "</tr>"
        )
    return "\n".join(rows)


def _film_order(
    roster: tuple[PackageRecord, ...], by_film: dict[str, list[Gadget]]
) -> list[str]:
    """Deterministic film ordering: roster order first, extras sorted after."""
    roster_slugs = [record.slug for record in roster]
    ordered = [slug for slug in roster_slugs if slug in by_film]
    extras = sorted(slug for slug in by_film if slug not in roster_slugs)
    return ordered + extras


def _gadget_rows(
    gadgets: GadgetRegistry | None, roster: tuple[PackageRecord, ...]
) -> str:
    """Per-film grouped gadget table (roster order, then extras, sorted)."""
    if gadgets is None or gadgets.count() == 0:
        return (
            '<tr><td colspan="3" class="muted">'
            "No gadgets registered yet — awaiting Q-branch (bond-api).</td></tr>"
        )
    by_film: dict[str, list[Gadget]] = {}
    for gadget in gadgets.all():
        by_film.setdefault(gadget.film, []).append(gadget)

    rows: list[str] = []
    for film in _film_order(roster, by_film):
        film_gadgets = by_film[film]
        rows.append(
            f'<tr class="film-group"><td colspan="3">'
            f"{escape(film)} — {len(film_gadgets)} gadget(s)</td></tr>"
        )
        for gadget in film_gadgets:
            rows.append(
                "<tr>"
                f"<td>{escape(gadget.name)}</td>"
                f"<td>{escape(gadget.purpose)}</td>"
                f'<td class="muted">{escape(gadget.film)}</td>'
                "</tr>"
            )
    return "\n".join(rows)


def _layer_rows(layers: tuple[LayerSummary, ...]) -> str:
    rows: list[str] = []
    for layer in layers:
        if layer.layer == "films":
            ready = f"{layer.ready_count}/{layer.total} ready"
        elif layer.ready is None:
            ready = "not probed"
        else:
            ready = "yes" if layer.ready else "no"
        mean = "—" if layer.coverage_mean is None else f"{layer.coverage_mean:.1f}%"
        rows.append(
            "<tr>"
            f"<td>{escape(layer.layer)}</td>"
            f"<td>{escape(layer.label)}</td>"
            f"<td>{escape(', '.join(layer.packages))}</td>"
            f"<td>{layer.total}</td>"
            f"<td>{escape(ready)}</td>"
            f"<td>{layer.ready_count}</td>"
            f"<td>{escape(mean)}</td>"
            "</tr>"
        )
    return "\n".join(rows)


def _audit_rows(ledger: MissionLedger, limit: int = AUDIT_TRAIL_LIMIT) -> str:
    """Most recent ledger transitions, newest first, deterministic tie-break."""
    entries = sorted(
        ledger.history, key=lambda entry: (entry.updated_at, entry.slug), reverse=True
    )[:limit]
    rows: list[str] = []
    for entry in entries:
        rows.append(
            "<tr>"
            f"<td><code>{escape(entry.slug)}</code></td>"
            f"<td>{escape(entry.phase.value)}</td>"
            f"<td>{escape(entry.updated_by)}</td>"
            f"<td>{escape(entry.updated_at.isoformat())}</td>"
            f"<td>{escape(entry.version)}</td>"
            f"<td>{escape(entry.note or '')}</td>"
            "</tr>"
        )
    return "\n".join(rows)


def build_situation_room(
    status: SuiteStatus,
    roster: tuple[PackageRecord, ...] = ROSTER,
    ledger: MissionLedger | None = None,
    gadgets: GadgetRegistry | None = None,
) -> str:
    """Render the situation-room HTML document.

    Deterministic given its inputs: the only time-dependent value is
    ``status.generated_at`` (inject a fixed ``now`` into
    :func:`bond_coordinator.status.build_status` for byte-stable output).
    """
    if ledger is None:
        ledger = MissionLedger(roster)

    # Counts-by-status cards, fixed order for determinism.
    cards = [
        _card("Total packages", status.total),
        _card("Scaffolded", status.counts_by_status[PackageStatus.SCAFFOLDED]),
        _card("Building", status.counts_by_status[PackageStatus.BUILDING]),
        _card("Ready", status.counts_by_status[PackageStatus.READY]),
        _card("Red", status.counts_by_status[PackageStatus.RED]),
        _card("Coverage (mean)", status.coverage.formatted_mean()),
        _card("Stale missions", len(status.stale_packages)),
        _card("Blocked packages", len(status.blocked_packages)),
    ]
    cards_html = "\n".join(cards)

    blocked_html = "None"
    if status.blocked_packages:
        blocked_html = ", ".join(
            f"{escape(item.slug)} ({escape(item.reason)})"
            for item in status.blocked_packages
        )

    dependency_html = (
        "available"
        if status.dependency_ready
        else "not yet built (pure-core mirror in use)"
    )

    layers_section = ""
    if status.layers:
        layers_section = f"""<section>
  <h2>Suite layers ({len(status.layers)})</h2>
  <table>
    <thead>
      <tr><th>Layer</th><th>Label</th><th>Packages</th><th>Total</th><th>Readiness</th><th>Ready count</th><th>Coverage mean</th></tr>
    </thead>
    <tbody>
{_layer_rows(status.layers)}
    </tbody>
  </table>
</section>
"""

    films_with = len({gadget.film for gadget in gadgets.all()}) if gadgets else 0
    roster_slugs = {record.slug for record in roster}
    roster_with = (
        len({gadget.film for gadget in gadgets.all() if gadget.film in roster_slugs})
        if gadgets
        else 0
    )
    gadget_summary = (
        f"<p>{films_with} film(s) have registered gadgets; "
        f"{len(roster) - roster_with} of {len(roster)} tracked films have none.</p>"
    )

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>{escape("BOND-COORDINATOR — Situation Room")}</title>
<style>
  body {{ font-family: -apple-system, "Segoe UI", Roboto, sans-serif; margin: 2rem; color: #0f172a; }}
  header h1 {{ margin-bottom: 0.2rem; }}
  header p {{ color: #475569; margin-top: 0; }}
  .cards {{ display: flex; flex-wrap: wrap; gap: 1rem; margin: 1.5rem 0; }}
  .card {{ border: 1px solid #cbd5e1; border-radius: 8px; padding: 0.8rem 1.2rem; min-width: 8rem; }}
  .card-label {{ display: block; font-size: 0.75rem; text-transform: uppercase; letter-spacing: 0.05em; color: #64748b; }}
  .card-value {{ font-size: 1.6rem; font-weight: 600; }}
  table {{ border-collapse: collapse; width: 100%; margin: 1rem 0 1rem; }}
  th, td {{ border: 1px solid #e2e8f0; padding: 0.45rem 0.6rem; text-align: left; }}
  th {{ background: #f1f5f9; }}
  code {{ background: #f8fafc; padding: 0.1rem 0.3rem; border-radius: 4px; }}
  .muted {{ color: #64748b; }}
  .timeline span {{ display: inline-block; width: 1.25rem; margin-right: 0.15rem;
      text-align: center; border-radius: 4px; font-size: 0.75rem; }}
  .tl-done {{ background: #2563eb; color: #ffffff; }}
  .tl-now {{ background: #f59e0b; color: #ffffff; }}
  .tl-todo {{ background: #e2e8f0; color: #94a3b8; }}
  .heat-ok {{ background: #dcfce7; font-weight: 600; }}
  .heat-warn {{ background: #fef9c3; font-weight: 600; }}
  .heat-bad {{ background: #fee2e2; font-weight: 600; }}
  .heat-unknown {{ background: #f1f5f9; color: #64748b; }}
  tr.film-group td {{ background: #eef2ff; font-weight: 600; }}
  footer {{ margin-top: 2rem; color: #64748b; font-size: 0.85rem; }}
</style>
</head>
<body>
<header>
  <h1>{escape("BOND-COORDINATOR")} — Situation Room</h1>
  <p>Codename <strong>{escape(COORDINATOR_CODENAME)}</strong> · Fleet status at {escape(status.generated_at.isoformat())}</p>
</header>

<section class="cards">
{cards_html}
</section>

<section>
  <h2>Blocked / stale flags</h2>
  <p>Blocked: <strong>{blocked_html}</strong></p>
  <p>Stale missions (unfinished, no update in 30 days): <strong>{escape(str(len(status.stale_packages)))}</strong></p>
  <p>Layer 1 dependency (bond-api): <strong>{dependency_html}</strong></p>
</section>

{layers_section}
<section>
  <h2>Film packages ({status.total})</h2>
  <table>
    <thead>
      <tr><th>#</th><th>Slug</th><th>Film</th><th>Codename</th><th>Status</th><th>Phase</th><th>Timeline</th><th>Last update</th><th>Coverage</th></tr>
    </thead>
    <tbody>
{_package_rows(roster, ledger)}
    </tbody>
  </table>
  <p class="muted">Coverage heat: <span class="heat-ok">≥90%</span> ·
    <span class="heat-warn">50–90%</span> · <span class="heat-bad">&lt;50%</span> ·
    <span class="heat-unknown">unmeasured</span>. Timeline cells: <span class="tl-done">done</span> ·
    <span class="tl-now">current</span> · <span class="tl-todo">ahead</span>.</p>
</section>

<section>
  <h2>Q-branch gadgets (per film)</h2>
  <table>
    <thead>
      <tr><th>Gadget</th><th>Purpose</th><th>Film</th></tr>
    </thead>
    <tbody>
{_gadget_rows(gadgets, roster)}
    </tbody>
  </table>
  {gadget_summary}
</section>

<section>
  <h2>Recent transitions (mission timeline, audit trail)</h2>
  <table>
    <thead>
      <tr><th>Slug</th><th>Phase</th><th>Agent</th><th>When</th><th>Version</th><th>Note</th></tr>
    </thead>
    <tbody>
{_audit_rows(ledger)}
    </tbody>
  </table>
  <p class="muted">Newest {AUDIT_TRAIL_LIMIT} of {len(ledger.history)} recorded transitions; full append-only trail persists in the ledger.</p>
</section>

<footer>
  Generated by <code>bond-coordinator</code> · PROJECT BOND suite · deterministic build (regenerate, never hand-edit)
</footer>
</body>
</html>
"""


def write_situation_room(html: str, path: Path) -> Path:
    """Write the situation-room document to ``path`` (utf-8), returning it."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(html, encoding="utf-8")
    return path
